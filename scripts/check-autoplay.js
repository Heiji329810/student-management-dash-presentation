async (page) => {
  const base = page.url().split(/[?#]/)[0];
  const checks = [];
  const assert = (value, label) => { if (!value) throw Error(label); checks.push(label); };
  const slide = () => page.locator('#jump').inputValue();
  const playing = () => page.locator('#playback').getAttribute('aria-pressed');
  await page.clock.install();
  await page.goto(base);
  await page.clock.runFor(13000);
  assert(await slide() === '0' && await playing() === 'false', 'Default starts paused');
  await page.keyboard.press('p');
  await page.clock.runFor(11999);
  assert(await slide() === '0', 'Default interval waits 12 seconds');
  await page.clock.runFor(1);
  assert(await slide() === '1', 'Default interval advances');
  await page.keyboard.press('p');
  await page.clock.runFor(24000);
  assert(await slide() === '1', 'P pauses');
  await page.keyboard.press('?');
  await page.locator('#interval').fill('3');
  await page.locator('#interval').press('Tab');
  await page.locator('#playback').focus();
  await page.keyboard.press('Enter');
  assert(await playing() === 'true', 'Play button keyboard activation');
  await page.clock.runFor(3000);
  assert(await slide() === '2', 'Configured interval advances');
  await page.clock.runFor(2000);
  await page.keyboard.press('ArrowRight');
  await page.clock.runFor(2000);
  assert(await slide() === '3', 'Manual navigation resets countdown');
  await page.clock.runFor(1000);
  assert(await slide() === '4', 'Manual selection gets full interval');
  await page.keyboard.press('End');
  await page.clock.runFor(3000);
  assert(await slide() === '0', 'Final slide loops to first');
  await page.keyboard.press('o');
  await page.clock.runFor(6000);
  assert(await playing() === 'false' && await slide() === '0', 'Overview pauses');
  await page.keyboard.press('p');
  assert(!await page.locator('body').evaluate(el => el.classList.contains('overview')), 'Play leaves overview');
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', {configurable:true,value:true}); document.dispatchEvent(new Event('visibilitychange')); });
  await page.clock.runFor(9000);
  assert(await slide() === '0', 'Hidden tab suspends playback');
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  await page.clock.runFor(3000);
  assert(await slide() === '1', 'Visible tab resumes with fresh interval');
  await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')));
  assert(await playing() === 'false', 'Printing pauses');
  for (const [value, expected] of [['1','3'],['999','120'],['nonsense','12'],['0','3'],['-5','3']]) {
    await page.goto(base + '?autoplay=1&interval=' + value + '#slide-62');
    assert(await page.locator('#interval').inputValue() === expected && await playing() === 'true', `URL interval ${value} normalizes to ${expected}`);
  }
  await page.goto(base + '?autoplay=1&interval=3#slide-62');
  await page.clock.runFor(3000);
  assert(await slide() === '0', 'URL autoplay loops');
  assert(await page.locator('#presentation-menu').isHidden(), 'Autoplay keeps controls hidden');
  await page.keyboard.press('p');
  await page.keyboard.press('?');
  await page.locator('#interval').focus();
  await page.keyboard.press('p');
  assert(await playing() === 'false', 'P in input does not trigger playback');
  await page.keyboard.press('Escape');
  await page.locator('body').click({position:{x:2,y:2}});
  await page.keyboard.press('p');
  await page.keyboard.press('f');
  assert(await page.evaluate(() => Boolean(document.fullscreenElement)) && await playing() === 'true', 'Fullscreen preserves playback');
  await page.keyboard.press('f');
  await page.keyboard.press('p');
  await page.clock.resume();
  return {checks, passed: checks.length};
}
